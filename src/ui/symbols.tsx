/** Association des icônes aux unités et thèmes. */
import type { ComponentType } from 'react';
import {
  IconBag,
  IconBook,
  IconBox,
  IconBriefcase,
  IconBuilding,
  IconChat,
  IconClock,
  IconHeart,
  IconHelp,
  IconHistory,
  IconHome,
  IconKey,
  IconLaptop,
  IconLayers,
  IconLeaf,
  IconLink,
  IconMap,
  IconPlane,
  IconRocket,
  IconScale,
  IconSmile,
  IconSparkles,
  IconSplit,
  IconSun,
  IconUsers,
  IconUtensils,
  IconWand,
  IconWarning,
  IconZap,
  IconCoffee,
} from './icons';

type Icon = ComponentType<{ size?: number; 'aria-hidden'?: boolean; className?: string }>;

const MAP: Record<string, Icon> = {
  clock: IconClock,
  history: IconHistory,
  help: IconHelp,
  box: IconBox,
  scale: IconScale,
  map: IconMap,
  rocket: IconRocket,
  key: IconKey,
  link: IconLink,
  wand: IconWand,
  split: IconSplit,
  layers: IconLayers,
  book: IconBook,
  chat: IconChat,
  sun: IconSun,
  briefcase: IconBriefcase,
  plane: IconPlane,
  utensils: IconUtensils,
  home: IconHome,
  heart: IconHeart,
  music: IconSparkles,
  laptop: IconLaptop,
  users: IconUsers,
  bag: IconBag,
  smile: IconSmile,
  building: IconBuilding,
  sparkles: IconSparkles,
  zap: IconZap,
  alert: IconWarning,
  leaf: IconLeaf,
  coffee: IconCoffee,
};

export function symbol(name: string): Icon {
  return MAP[name] ?? IconBook;
}
